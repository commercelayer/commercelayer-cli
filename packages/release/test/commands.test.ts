import { expect } from 'chai'
import { labelerConfig } from '../src/commands/labels.ts'
import { surfaceDiff } from '../src/commands/manifest.ts'
import { withMaintenanceNote } from '../src/commands/notes.ts'
import { dependenciesToPublish, isConcurrentPublish } from '../src/commands/publish.ts'
import { planShip } from '../src/commands/ship.ts'
import { withWorkspaceDeps } from '../src/commands/try.ts'
import { addChangedDependencies, bump, releasePrBody } from '../src/commands/version.ts'
import { pkg } from './helpers.ts'

describe('version', () => {
  it('bumps by level', () => {
    expect(bump('6.9.9', 'patch')).to.equal('6.9.10')
    expect(bump('6.9.9', 'minor')).to.equal('6.10.0')
    expect(bump('6.9.9', 'major')).to.equal('7.0.0')
  })
  it('releases a prerelease left in a package.json as its stable version', () => {
    expect(bump('7.0.0-beta.1', 'patch')).to.equal('7.0.0')
    expect(bump('7.0.0-beta.1', 'major')).to.equal('7.0.0')
  })

  it('adds the changed workspace dependencies of the selected packages, transitively', () => {
    const core = pkg('core', '6.0.0')
    const ux = pkg('ux', '2.0.0', ['core'])
    const tags = pkg('tags', '3.0.0', ['ux'])
    const other = pkg('other', '1.0.0')
    const candidate = (p: typeof core, next: string) => ({ pkg: p, commits: [['fix: x']], level: 'patch' as const, why: '', next })
    const candidates = [candidate(core, '6.0.1'), candidate(ux, '2.0.1'), candidate(tags, '3.0.1'), candidate(other, '1.0.1')]
    const selected = [{ ...candidates[2], version: '3.1.0' }]
    const added = addChangedDependencies(selected, candidates)
    expect(selected.map((s) => `${s.pkg.dir}@${s.version}`)).to.deep.equal(['tags@3.1.0', 'ux@2.0.1', 'core@6.0.1'])
    expect(added.map((a) => `${a.added.pkg.dir}<-${a.by.pkg.dir}`)).to.deep.equal(['ux<-tags', 'core<-ux'])
  })
})

describe('publish', () => {
  const core = pkg('core', '6.0.0')
  const ux = pkg('ux', '2.0.0', ['core'])
  const tags = pkg('tags', '3.0.0', ['core', 'ux'])
  const packages = [core, ux, tags]

  it('publishes the dependencies not on npm first', () => {
    const deps = dependenciesToPublish(tags, packages, { published: () => false, tags: new Set(['core-v6.0.0', 'ux-v2.0.0']) })
    expect(deps.map((p) => p.dir)).to.deep.equal(['core', 'ux'])
  })
  it('skips the dependencies already on npm', () => {
    const deps = dependenciesToPublish(tags, packages, { published: (p) => p.dir === 'core', tags: new Set(['ux-v2.0.0']) })
    expect(deps.map((p) => p.dir)).to.deep.equal(['ux'])
  })
  it('stops on a dependency without a release tag', () => {
    expect(() => dependenciesToPublish(tags, packages, { published: () => false, tags: new Set(['ux-v2.0.0']) })).to.throw(/@cl\/tags needs @cl\/core@6.0.0.*no core-v6.0.0 release tag/)
  })
  it('stops on a private dependency', () => {
    const dev = pkg('dev', '1.0.0', [], { private: true })
    expect(() => dependenciesToPublish(pkg('x', '1.0.0', ['dev']), [dev], { published: () => false, tags: new Set() })).to.throw(/private @cl\/dev/)
  })
})

describe('manifest', () => {
  it('reports removed and added commands, flags and args', () => {
    const previous = { commands: { a: { flags: { x: {}, y: {} }, args: { id: {} } }, gone: {} } }
    const current = { commands: { a: { flags: { x: {}, z: {} }, args: {} }, fresh: {} } }
    expect(surfaceDiff(previous, current)).to.deep.equal({
      removed: ['flag a --y', 'arg a id', 'command gone'],
      added: ['flag a --z', 'command fresh'],
    })
  })
})

describe('notes', () => {
  it('adds a maintenance note when no section is shown', () => {
    expect(withMaintenanceNote('## 1.0.1', 'x-v1.0.0')).to.match(/Maintenance release: no changes to features or fixes since x-v1.0.0/)
    expect(withMaintenanceNote('## 1.1.0\n\n### Features\n\n* a', 'x-v1.0.0')).to.not.match(/Maintenance/)
  })
})

describe('labels', () => {
  it('has one pkg:<dir> label per package', () => {
    const config = labelerConfig([{ dir: 'tags', path: 'plugins/tags' }])
    expect(config).to.match(/^# Generated by/)
    expect(config).to.contain("'pkg:tags':\n  - changed-files:\n      - any-glob-to-any-file:\n          - 'plugins/tags/**'\n")
  })
})

describe('try', () => {
  it('installs the workspace dependencies of the chosen packages', () => {
    const core = pkg('core', '1.0.0')
    const ux = pkg('ux', '1.0.0', ['core'])
    const tags = pkg('tags', '1.0.0', ['ux'])
    const orders = pkg('orders', '1.0.0', ['core'])
    expect([...withWorkspaceDeps([tags], [core, ux, tags, orders])].map((p) => p.dir)).to.deep.equal(['tags', 'ux', 'core'])
  })
})

describe('publish of a concurrent release', () => {
  it('recognizes the npm conflict of a version being published by another run', () => {
    expect(isConcurrentPublish('npm error code E409\nnpm error 409 Conflict - PUT … - Cannot publish over previously staged version "5.12.0".')).to.equal(true)
    expect(isConcurrentPublish('npm error code E403\nnpm error 403 Forbidden')).to.equal(false)
  })
})

describe('ship', () => {
  const core = pkg('core', '6.0.0')
  const ux = pkg('ux', '2.0.0', ['core'])
  const tags = pkg('tags', '3.0.0', ['core', 'ux'])
  const exportsPkg = pkg('exports', '4.0.9', ['core'])

  it('groups the pending versions by the commit that set them, oldest first, dependencies first', () => {
    const groups = planShip([
      { pkg: tags, commit: 'bbb', time: 200 },
      { pkg: exportsPkg, commit: 'aaa', time: 100 },
      { pkg: ux, commit: 'bbb', time: 200 },
      { pkg: core, commit: 'bbb', time: 200 },
    ])
    expect(groups.map((g) => g.commit)).to.deep.equal(['aaa', 'bbb'])
    expect(groups[1].packages.map((p) => p.dir)).to.deep.equal(['core', 'ux', 'tags'])
  })

  it('has nothing to release when every version is on npm', () => {
    expect(planShip([])).to.deep.equal([])
  })
})

describe('release PR body', () => {
  const entry = (name: string, notes: string) => ({ name: `@cl/${name}`, path: `plugins/${name}`, from: '1.0.0', to: '2.0.0', tag: `${name}-v2.0.0`, notes })

  it('lists the bumps and the release notes of each package', () => {
    const body = releasePrBody([entry('tags', '## 2.0.0\n\n### Features\n\n* tags')])
    expect(body).to.contain('- `@cl/tags` 1.0.0 → **2.0.0** (`tags-v2.0.0`)')
    expect(body).to.contain('<details><summary><b>@cl/tags</b> 2.0.0</summary>')
    expect(body).to.contain('### Features')
    expect(body).to.contain('publish.yml')
  })

  it('stays within GitHub limit, cutting long notes with a link to the commits', () => {
    const long = Array.from({ length: 5000 }, (_, i) => `* change ${i}`).join('\n')
    const body = releasePrBody(Array.from({ length: 18 }, (_, i) => entry(`p${i}`, long)))
    expect(body.length).to.be.lessThan(65_536)
    expect(body).to.contain('… [all the changes](https://github.com/commercelayer/commercelayer-cli/commits/main/plugins/p0)')
  })
})
